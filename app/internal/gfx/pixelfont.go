package gfx

import (
	"strings"
	"unicode/utf8"
)

// PixelFont is a block font: 5x7 cells, each lit cell drawn as an SX x SY
// block, the way an old deck's character generator drew its on-screen
// display. Upper case only: lower case and accented Latin letters are
// drawn as their capitals, anything else it has no cell for as '?'. Its
// cells are this file's own drawing, not a font's.
type PixelFont struct{ SX, SY int }

// Height is the cell height in pixels.
func (f PixelFont) Height() int { return 7 * f.SY }

// advance is a cell and the one-block gap after it.
func (f PixelFont) advance() int { return 6 * f.SX }

// Width measures s in pixels, without the gap after its last cell.
func (f PixelFont) Width(s string) int {
	n := utf8.RuneCountInString(s)
	if n == 0 {
		return 0
	}
	return n*f.advance() - f.SX
}

// Fit truncates s with an ellipsis so it fits in maxW pixels.
func (f PixelFont) Fit(s string, maxW int) string {
	if f.Width(s) <= maxW {
		return s
	}
	runes := []rune(s)
	for n := len(runes) - 1; n > 0; n-- {
		t := strings.TrimRight(string(runes[:n]), " ")
		if f.Width(t+"...") <= maxW {
			return t + "..."
		}
	}
	return ""
}

// PixelText draws s with its cell top at y, each block with a hard shadow
// two pixels right and down (none when shadow is col), and returns the x
// after its last cell.
func (c *Canvas) PixelText(x, y int, f PixelFont, col, shadow Color, s string) int {
	if shadow != col {
		c.pixelRun(x+2, y+2, f, shadow, s)
	}
	return c.pixelRun(x, y, f, col, s)
}

func (c *Canvas) pixelRun(x, y int, f PixelFont, col Color, s string) int {
	for _, r := range s {
		cell := pixelCell(r)
		for row, bits := range cell {
			for b := 0; b < 5; b++ {
				if bits&(0x10>>b) != 0 {
					c.Fill(x+b*f.SX, y+row*f.SY, f.SX, f.SY, col)
				}
			}
		}
		x += f.advance()
	}
	return x
}

// The symbols with cells of their own, for the deck's transport words.
const (
	PixelPlay   = '▶'
	PixelRewind = '◀'
	PixelPause  = '⏸'
	PixelStop   = '■'
	PixelTick   = '✓'
)

// pixelCell is r's cell, seven rows of five bits, the left column 0x10.
func pixelCell(r rune) [7]byte {
	if r >= 'a' && r <= 'z' {
		r -= 'a' - 'A'
	}
	if r >= 0xC0 && r <= 0xFF {
		r = rune(latinBase[r-0xC0])
	}
	if r >= ' ' && r <= 'Z' {
		return pixelASCII[r-' ']
	}
	switch r {
	case '[':
		return [7]byte{0x0E, 0x08, 0x08, 0x08, 0x08, 0x08, 0x0E}
	case ']':
		return [7]byte{0x0E, 0x02, 0x02, 0x02, 0x02, 0x02, 0x0E}
	case '_':
		return [7]byte{0, 0, 0, 0, 0, 0, 0x1F}
	case '|':
		return [7]byte{0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04}
	case '`', '‘', '’':
		return pixelASCII['\''-' ']
	case '“', '”':
		return pixelASCII['"'-' ']
	case '–', '—':
		return pixelASCII['-'-' ']
	case PixelPlay:
		return [7]byte{0x10, 0x18, 0x1C, 0x1E, 0x1C, 0x18, 0x10}
	case PixelRewind:
		return [7]byte{0x01, 0x03, 0x07, 0x0F, 0x07, 0x03, 0x01}
	case PixelPause:
		return [7]byte{0x1B, 0x1B, 0x1B, 0x1B, 0x1B, 0x1B, 0x1B}
	case PixelStop:
		return [7]byte{0, 0x1F, 0x1F, 0x1F, 0x1F, 0x1F, 0}
	case PixelTick:
		return [7]byte{0, 0x01, 0x02, 0x14, 0x08, 0, 0}
	}
	return pixelASCII['?'-' ']
}

